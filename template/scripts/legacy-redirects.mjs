#!/usr/bin/env node
/**
 * Old WordPress URLs as STATIC `_redirects` rules, so the asset layer answers them and the Worker
 * never runs (kit 0.1.25, the 2026-11-22 Worker-cost fix first made on 123achei).
 *
 *   node --experimental-strip-types scripts/legacy-redirects.mjs [assetsDir]
 *
 * Runs in the build after the legacy uploads are staged and linked into the output, because the
 * targets are the files actually deployed. Appends one generated block to `<assetsDir>/_redirects`
 * (the copy Astro made of public/_redirects; the hand-written file is not touched):
 *
 *  1. every attachment page in src/data/attachment-redirects.json (`/slug/`, as WordPress
 *     published it) → its parent, 301. The Worker also answered the slashless `/slug`; those
 *     extra rules would exceed the cap, so `/slug` is now a real 404;
 *  2. every old upload URL the recon knows (recon/wp-json media incl. every WordPress size, and
 *     every /wp-content/uploads/ reference in recon/html) that is not deployed as it is → the
 *     deployed file the Worker's own fallback picked (src/lib/upload-fallback.ts: original →
 *     .webp, `-WxH` / `-scaled` variant → the hosted original's WebP), 301. No target → no rule
 *     (a real 404, as before).
 *
 * Why: with `assets.not_found_handling: "none"` every asset miss ran the Worker; on 2026-11-22
 * Applebot crawled ~86k dead directory-site URLs and the account went over the Workers Free
 * daily limit. Now `not_found_handling: "404-page"` with `run_worker_first: ["/api/*"]` serves
 * misses from assets, and these rules replace what the Worker's legacyRedirect() did.
 *
 * FAILS when: a source is a deployed file (a redirect would shadow it: `_redirects` wins over
 * assets), a target is not deployed, a source repeats a hand-written rule, or the file would
 * exceed Cloudflare's 2,000 static rules.
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readMigrationManifest } from './lib/aw-migration.mjs';
import { ATTACHMENTS_FILE, UPLOADS, assetsDirectory, ownHosts, uploadTokenRegex, walk } from './lib/legacy-media.mjs';
import { uploadFallbackDeployed } from '../src/lib/upload-fallback.ts';

const MAX_STATIC = 2000;
const MARK = '# ── Generated by scripts/legacy-redirects.mjs (do not edit; see the script header) ──';

const dir = process.argv[2] ?? assetsDirectory();
const file = join(dir, '_redirects');
const problems = [];
if (!existsSync(dir)) {
  console.error(`✗ legacy-redirects: ${dir} does not exist; run the build first.`);
  process.exit(1);
}

/** A deployed file for a (decoded) URL path, the way the asset layer resolves it. */
const deployed = (path) => {
  const local = join(dir, path);
  if (existsSync(local) && statSync(local).isFile()) return true;
  if (path.endsWith('/')) return existsSync(join(local, 'index.html'));
  return existsSync(`${local}.html`) || existsSync(join(local, 'index.html'));
};

const existing = existsSync(file) ? readFileSync(file, 'utf8') : '';
const handWritten = (existing.includes(MARK) ? existing.slice(0, existing.indexOf(MARK)) : existing).trimEnd();
const handSources = new Set(
  handWritten.split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#')).map((l) => l.split(/\s+/)[0]),
);

const rules = new Map(); // encoded source → [target, why]
const add = (decodedSource, target, why) => {
  const source = encodeURI(decodedSource);
  if (handSources.has(source) || rules.has(source)) return;
  if (deployed(decodedSource)) {
    problems.push(`${decodedSource} is a deployed file; a redirect would shadow it (${why}).`);
    return;
  }
  let decodedTarget = target;
  try { decodedTarget = decodeURI(target); } catch { /* keep */ }
  if (!deployed(decodedTarget)) {
    problems.push(`${decodedSource} → ${target}: the target is not deployed (${why}).`);
    return;
  }
  if (source === target) {
    problems.push(`${decodedSource} redirects to itself (${why}).`);
    return;
  }
  rules.set(source, [target, why]);
};

// 1. Attachment pages.
const attachments = existsSync(ATTACHMENTS_FILE) ? JSON.parse(readFileSync(ATTACHMENTS_FILE, 'utf8')) : {};
// Slash form only: WordPress published every attachment URL with the slash, and the slashless
// duplicates (one more rule per page) could take the file over the 2,000-rule cap. `/slug` is now a real 404.
for (const [page, target] of Object.entries(attachments)) add(page, target, 'attachment page');

// 2. Old upload URLs the recon knows.
const known = new Set();
const remember = (raw) => {
  try {
    const url = new URL(raw.replace(/\\\//g, '/'), 'https://old.invalid');
    if (!url.pathname.startsWith(`/${UPLOADS}/`)) return;
    known.add(decodeURIComponent(url.pathname));
  } catch { /* not a URL */ }
};
if (existsSync('recon/wp-json')) {
  for (const name of readdirSync('recon/wp-json')) {
    if (!/^media.*\.json$/.test(name)) continue;
    for (const item of JSON.parse(readFileSync(join('recon/wp-json', name), 'utf8'))) {
      if (item?.source_url) remember(item.source_url);
      for (const size of Object.values(item?.media_details?.sizes ?? {})) if (size?.source_url) remember(size.source_url);
    }
  }
}
if (existsSync('recon/html')) {
  // The same tokenizer legacy-media-stage uses: own hosts only (a third-party WordPress image is not ours).
  const token = uploadTokenRegex([...ownHosts(readMigrationManifest())]);
  for (const path of walk('recon/html')) {
    for (const m of readFileSync(path, 'utf8').matchAll(token)) remember(m[2]);
  }
}
const exists = async (p) => deployed(p);
let noTarget = 0;
for (const path of [...known].sort()) {
  if (deployed(path)) continue; // served as it is
  const target = await uploadFallbackDeployed(encodeURI(path), exists);
  if (target) add(path, target, 'old upload URL');
  else noTarget += 1;
}

const handCount = handSources.size;
if (handCount + rules.size > MAX_STATIC) {
  problems.push(`${handCount} hand-written + ${rules.size} generated = ${handCount + rules.size} static rules; Cloudflare caps _redirects at ${MAX_STATIC}.`);
}
if (problems.length) {
  console.error(`✗ legacy-redirects:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

const lines = [...rules].map(([source, [target]]) => `${source} ${target} 301`);
writeFileSync(file, `${handWritten}\n\n${MARK}\n${lines.join('\n')}\n`);
const uploads = [...rules.values()].filter(([, why]) => why === 'old upload URL').length;
console.log(`✓ legacy-redirects: ${rules.size} rules (${rules.size - uploads} attachment pages, ${uploads} old upload URLs; ${noTarget} known upload URLs have no deployed target and stay 404) + ${handCount} hand-written = ${handCount + rules.size}/${MAX_STATIC} → ${file}`);
